CREATE TABLE IF NOT EXISTS `#__adrianjdownloads_files` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `catid` int NOT NULL DEFAULT 0,
  `title` varchar(255) NOT NULL DEFAULT '',
  `alias` varchar(400) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT '',
  `description` mediumtext,
  `file_name` varchar(255) NOT NULL DEFAULT '',
  `file_original` varchar(255) NOT NULL DEFAULT '',
  `file_size` bigint unsigned NOT NULL DEFAULT 0,
  `file_mime` varchar(150) NOT NULL DEFAULT '',
  `external_url` varchar(2048) NOT NULL DEFAULT '',
  `version` varchar(50) NOT NULL DEFAULT '',
  `author` varchar(255) NOT NULL DEFAULT '',
  `downloads` int unsigned NOT NULL DEFAULT 0,
  `hits` int unsigned NOT NULL DEFAULT 0,
  `state` tinyint NOT NULL DEFAULT 0,
  `featured` tinyint unsigned NOT NULL DEFAULT 0,
  `access` int unsigned NOT NULL DEFAULT 1,
  `access_download` int unsigned NOT NULL DEFAULT 1,
  `language` varchar(7) NOT NULL DEFAULT '*',
  `ordering` int NOT NULL DEFAULT 0,
  `created` datetime NOT NULL,
  `created_by` int unsigned NOT NULL DEFAULT 0,
  `modified` datetime NOT NULL,
  `modified_by` int unsigned NOT NULL DEFAULT 0,
  `publish_up` datetime,
  `publish_down` datetime,
  `checked_out` int unsigned,
  `checked_out_time` datetime,
  `params` text NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_catid` (`catid`),
  KEY `idx_state` (`state`),
  KEY `idx_access` (`access`),
  KEY `idx_language` (`language`),
  KEY `idx_alias` (`alias`(191)),
  KEY `idx_checkout` (`checked_out`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 DEFAULT COLLATE=utf8mb4_unicode_ci;
